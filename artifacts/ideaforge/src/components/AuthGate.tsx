export function AuthGate({ children }: { children: React.ReactNode }) {
  const [location] = useLocation();
  const [user, setUser] = useState<IdeaForgeUser | null>(() => {
    try {
      const raw = localStorage.getItem(USER_STORAGE_KEY);
      return raw ? JSON.parse(raw) : null;
    } catch {
      return null;
    }
  });
  const [token, setToken] = useState<string | null>(() => {
    try {
      return localStorage.getItem(TOKEN_STORAGE_KEY);
    } catch {
      return null;
    }
  });

  const [mode, setMode] = useState<'login' | 'register'>('login');
  const [username, setUsername] = useState('');
  const [password, setPassword] = useState('');
  const [displayName, setDisplayName] = useState('');
  const [consentDataProcessing, setConsentDataProcessing] = useState(false);
  const [consentAiDisclaimer, setConsentAiDisclaimer] = useState(false);
  const [errorMsg, setErrorMsg] = useState<string | null>(null);
  const [isSubmitting, setIsSubmitting] = useState(false);
  const [legalModal, setLegalModal] = useState<'privacy' | 'terms' | null>(null);

  const [isTransitioning, setIsTransitioning] = useState(false);
  const [loadingProgress, setLoadingProgress] = useState(0);

  // Verify token session in background if non-guest token exists
  useEffect(() => {
    if (!token || token === 'guest-local-token') return;
    let cancelled = false;
    fetch('/api/auth/me', {
      headers: { Authorization: `Bearer ${token}` },
    })
      .then(async (res) => {
        if (cancelled) return;
        if (res.status === 401) {
          localStorage.removeItem(TOKEN_STORAGE_KEY);
          localStorage.removeItem(USER_STORAGE_KEY);
          setToken(null);
          setUser(null);
        } else if (res.ok) {
          const data = await res.json();
          if (data?.user) {
            setUser(data.user);
            localStorage.setItem(USER_STORAGE_KEY, JSON.stringify(data.user));
          }
        }
      })
      .catch(() => {
        // Offline / local fallback: preserve local session
      });
    return () => {
      cancelled = true;
    };
  }, [token]);

  const triggerForgeTransition = (nextToken: string, nextUser: IdeaForgeUser) => {
    localStorage.setItem(TOKEN_STORAGE_KEY, nextToken);
    localStorage.setItem(USER_STORAGE_KEY, JSON.stringify(nextUser));

    const prefersReducedMotion =
      typeof window !== 'undefined' &&
      window.matchMedia?.('(prefers-reduced-motion: reduce)').matches;

    if (prefersReducedMotion) {
      setToken(nextToken);
      setUser(nextUser);
      return;
    }

    setIsTransitioning(true);
    setLoadingProgress(15);

    const step1 = setTimeout(() => setLoadingProgress(55), 300);
    const step2 = setTimeout(() => setLoadingProgress(90), 650);
    const step3 = setTimeout(() => setLoadingProgress(100), 900);
    const finish = setTimeout(() => {
      setIsTransitioning(false);
      setToken(nextToken);
      setUser(nextUser);
    }, 1050);

    return () => {
      clearTimeout(step1);
      clearTimeout(step2);
      clearTimeout(step3);
      clearTimeout(finish);
    };
  };

  const bothConsentsChecked = consentDataProcessing && consentAiDisclaimer;

  const handleAuthSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    setErrorMsg(null);

    if (!bothConsentsChecked) {
      setErrorMsg('Please accept both the Data Processing Consent and AI Deliverable Disclaimer checkboxes to continue.');
      return;
    }

    const cleanUsername = username.trim();
    if (cleanUsername.length < 3) {
      setErrorMsg('Username must be at least 3 characters.');
      return;
    }
    if (password.length < 6) {
      setErrorMsg('Password must be at least 6 characters.');
      return;
    }

    setIsSubmitting(true);
    try {
      const endpoint = mode === 'register' ? '/api/auth/register' : '/api/auth/login';
      const payload =
        mode === 'register'
          ? {
              username: cleanUsername,
              password,
              displayName: displayName.trim() || cleanUsername,
              consentAccepted: true,
            }
          : {
              username: cleanUsername,
              password,
            };

      const res = await fetch(endpoint, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(payload),
      });

      if (res.ok) {
        const data = await res.json();
        setIsSubmitting(false);
        triggerForgeTransition(data.token, data.user);
        return;
      }

      if (res.status >= 400 && res.status < 500) {
        const errBody = await res.json().catch(() => ({}));
        setErrorMsg(errBody.error || `Authentication failed (${res.status}).`);
        setIsSubmitting(false);
        return;
      }

      // 5xx / proxy offline fallback
      const fallbackUser: IdeaForgeUser = {
        id: Date.now(),
        username: cleanUsername,
        displayName: displayName.trim() || cleanUsername,
        consentAccepted: true,
        consentAcceptedAt: new Date().toISOString(),
      };
      setIsSubmitting(false);
      triggerForgeTransition(`local-token-${Date.now()}`, fallbackUser);
    } catch {
      // Offline network fallback
      const fallbackUser: IdeaForgeUser = {
        id: Date.now(),
        username: cleanUsername,
        displayName: displayName.trim() || cleanUsername,
        consentAccepted: true,
        consentAcceptedAt: new Date().toISOString(),
      };
      setIsSubmitting(false);
      triggerForgeTransition(`local-token-${Date.now()}`, fallbackUser);
    }
  };

  const handleGuestContinue = () => {
    setErrorMsg(null);
    if (!bothConsentsChecked) {
      setErrorMsg('Please check both Consent and AI Deliverable Disclaimer boxes before entering as Guest Builder.');
      return;
    }
    const guestUser: IdeaForgeUser = {
      id: 'guest',
      username: 'guest',
      displayName: 'Guest Builder',
      consentAccepted: true,
      consentAcceptedAt: new Date().toISOString(),
      isGuest: true,
    };
    triggerForgeTransition('guest-local-token', guestUser);
  };

  const signOut = () => {
    localStorage.removeItem(TOKEN_STORAGE_KEY);
    localStorage.removeItem(USER_STORAGE_KEY);
    setToken(null);
    setUser(null);
    setPassword('');
  };

  const exportAccountData = async () => {
    let exportPayload: unknown = {
      user,
      generations: [],
      exportedAt: new Date().toISOString(),
    };

    if (token && token !== 'guest-local-token') {
      try {
        const res = await fetch('/api/account/export', {
          headers: { Authorization: `Bearer ${token}` },
        });
        if (res.ok) {
          exportPayload = await res.json();
        }
      } catch {
        // Use fallback local export payload
      }
    }

    const blob = new Blob([JSON.stringify(exportPayload, null, 2)], {
      type: 'application/json',
    });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `ideaforge-account-export-${new Date().toISOString().slice(0, 10)}.json`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  };

  const deleteAccount = async () => {
    if (token && token !== 'guest-local-token') {
      try {
        await fetch('/api/account', {
          method: 'DELETE',
          headers: { Authorization: `Bearer ${token}` },
        });
      } catch {
        // Proceed with local cleanup even if backend is unreachable
      }
    }
    signOut();
  };

  // Allow direct navigation to /privacy or /terms even when unauthenticated
  if (!user && (location === '/privacy' || location === '/terms')) {
    return (
      <div className="min-h-screen bg-background flex flex-col items-center justify-center p-4">
        <LegalDocumentView
          type={location === '/privacy' ? 'privacy' : 'terms'}
          onClose={() => window.history.back()}
        />
      </div>
    );
  }

  if (isTransitioning) {
    return <ForgeLoadingScreen progress={loadingProgress} />;
  }

  if (!user || !token) {
    return (
      <div className="min-h-screen bg-background text-foreground flex flex-col justify-between p-4 md:p-8 selection:bg-primary selection:text-primary-foreground">
        <div className="max-w-lg w-full mx-auto my-auto space-y-6">
          <div className="text-center space-y-2">
            <div className="inline-flex items-center gap-2 px-3 py-1 rounded-full bg-primary/10 text-primary font-mono text-xs font-bold uppercase tracking-wider">
              <Sparkles className="w-3.5 h-3.5" />
              AI Product Foundry
            </div>
            <h1 className="text-4xl font-display font-extrabold tracking-tight">
              Welcome to <span className="text-primary">IdeaForge</span>
            </h1>
            <p className="text-sm text-muted-foreground max-w-md mx-auto">
              Transform raw product concepts into structured PRDs, slide decks, interactive charts, and web app prototypes.
            </p>
          </div>

          {legalModal ? (
            <LegalDocumentView type={legalModal} onClose={() => setLegalModal(null)} />
          ) : (
            <Card className="border-2 shadow-xl">
              <CardHeader className="pb-4">
                <div className="grid grid-cols-2 gap-2 p-1 bg-muted rounded-lg mb-2" role="tablist" aria-label="Authentication mode">
                  <button
                    type="button"
                    role="tab"
                    aria-selected={mode === 'login'}
                    onClick={() => {
                      setMode('login');
                      setErrorMsg(null);
                    }}
                    className={`py-2 text-sm font-bold font-display rounded-md transition-all ${
                      mode === 'login'
                        ? 'bg-background text-foreground shadow-sm'
                        : 'text-muted-foreground hover:text-foreground'
                    }`}
                  >
                    Sign In
                  </button>
                  <button
                    type="button"
                    role="tab"
                    aria-selected={mode === 'register'}
                    onClick={() => {
                      setMode('register');
                      setErrorMsg(null);
                    }}
                    className={`py-2 text-sm font-bold font-display rounded-md transition-all ${
                      mode === 'register'
                        ? 'bg-background text-foreground shadow-sm'
                        : 'text-muted-foreground hover:text-foreground'
                    }`}
                  >
                    Create Account
                  </button>
                </div>
                <CardTitle className="text-xl font-display">
                  {mode === 'login' ? 'Sign in to your Foundry' : 'Create your Foundry Account'}
                </CardTitle>
                <CardDescription>
                  {mode === 'login'
                    ? 'Enter your credentials and confirm AI workspace disclosures below.'
                    : 'Register an account to persist, export, or manage your forged deliverables.'}
                </CardDescription>
              </CardHeader>

              <CardContent className="space-y-5">
                {errorMsg && (
                  <div
                    role="alert"
                    className="bg-destructive/10 border border-destructive/30 text-destructive rounded-lg p-3 text-xs font-medium flex items-start gap-2.5"
                  >
                    <AlertTriangle className="w-4 h-4 shrink-0 mt-0.5" />
                    <span>{errorMsg}</span>
                  </div>
                )}

                {/* Mandatory Pre-Use Consent & AI Deliverable Disclaimers */}
                <div className="rounded-lg border bg-muted/40 p-4 space-y-3">
                  <div className="flex items-center gap-2 text-xs font-mono font-bold uppercase tracking-wider text-primary">
                    <ShieldCheck className="w-4 h-4" />
                    Mandatory Data &amp; AI Deliverable Disclosures
                  </div>

                  <label
                    htmlFor="consent-data-checkbox"
                    className="flex items-start gap-3 text-xs leading-relaxed cursor-pointer select-none"
                  >
                    <input
                      id="consent-data-checkbox"
                      type="checkbox"
                      checked={consentDataProcessing}
                      onChange={(e) => setConsentDataProcessing(e.target.checked)}
                      className="mt-0.5 h-4 w-4 rounded border-input accent-primary shrink-0"
                    />
                    <span>
                      I consent to IdeaForge processing my product ideas via Gemini / OpenRouter AI models and storing generated deliverables.
                    </span>
                  </label>

                  <label
                    htmlFor="consent-disclaimer-checkbox"
                    className="flex items-start gap-3 text-xs leading-relaxed cursor-pointer select-none"
                  >
                    <input
                      id="consent-disclaimer-checkbox"
                      type="checkbox"
                      checked={consentAiDisclaimer}
                      onChange={(e) => setConsentAiDisclaimer(e.target.checked)}
                      className="mt-0.5 h-4 w-4 rounded border-input accent-primary shrink-0"
                    />
                    <span>
                      I understand that generated PRDs, slide decks, financial charts, and web app prototypes are AI-generated drafts for ideation and require human verification.
                    </span>
                  </label>

                  <div className="pt-1 flex items-center gap-4 text-[11px] text-muted-foreground font-mono">
                    <button
                      type="button"
                      onClick={() => setLegalModal('privacy')}
                      className="underline hover:text-primary inline-flex items-center gap-1"
                    >
                      <FileText className="w-3 h-3" /> Privacy Policy
                    </button>
                    <button
                      type="button"
                      onClick={() => setLegalModal('terms')}
                      className="underline hover:text-primary inline-flex items-center gap-1"
                    >
                      <FileText className="w-3 h-3" /> Terms of Service
                    </button>
                  </div>
                </div>

                <form id="ideaforge-auth-form" onSubmit={handleAuthSubmit} className="space-y-3.5">
                  <div className="space-y-1.5">
                    <label htmlFor="auth-username" className="text-xs font-bold uppercase tracking-wider text-muted-foreground block">
                      Username
                    </label>
                    <Input
                      id="auth-username"
                      type="text"
                      autoComplete="username"
                      placeholder="e.g. ada_lovelace"
                      value={username}
                      onChange={(e) => setUsername(e.target.value)}
                      required
                    />
                  </div>

                  {mode === 'register' && (
                    <div className="space-y-1.5">
                      <label htmlFor="auth-displayname" className="text-xs font-bold uppercase tracking-wider text-muted-foreground block">
                        Display Name (optional)
                      </label>
                      <Input
                        id="auth-displayname"
                        type="text"
                        autoComplete="name"
                        placeholder="e.g. Ada Lovelace"
                        value={displayName}
                        onChange={(e) => setDisplayName(e.target.value)}
                      />
                    </div>
                  )}

                  <div className="space-y-1.5">
                    <label htmlFor="auth-password" className="text-xs font-bold uppercase tracking-wider text-muted-foreground block">
                      Password
                    </label>
                    <Input
                      id="auth-password"
                      type="password"
                      autoComplete={mode === 'register' ? 'new-password' : 'current-password'}
                      placeholder="Minimum 6 characters"
                      value={password}
                      onChange={(e) => setPassword(e.target.value)}
                      required
                    />
                  </div>

                  <Button
                    type="submit"
                    className="w-full font-display font-bold uppercase tracking-wide h-10"
                    disabled={isSubmitting || !bothConsentsChecked}
                  >
                    <Lock className="w-4 h-4 mr-2" />
                    {isSubmitting
                      ? 'Authenticating...'
                      : mode === 'login'
                        ? 'Sign In & Launch Foundry'
                        : 'Create Account & Launch Foundry'}
                  </Button>
                </form>
              </CardContent>

              <CardFooter className="flex flex-col gap-3 border-t bg-muted/20 pt-4">
                <Button
                  type="button"
                  variant="outline"
                  className="w-full font-display font-bold text-xs uppercase tracking-wider"
                  onClick={handleGuestContinue}
                  disabled={!bothConsentsChecked}
                >
                  <UserCheck className="w-4 h-4 mr-2 text-primary" />
                  Continue as Guest Builder
                </Button>
              </CardFooter>
            </Card>
          )}
        </div>

        <footer className="text-center text-xs text-muted-foreground font-mono py-4">
          IdeaForge AI Deliverable Foundry &bull; Human verification required for all generated outputs.
        </footer>
      </div>
    );
  }

  return (
    <AuthContext.Provider value={{ user, token, signOut, deleteAccount, exportAccountData }}>
      {children}
    </AuthContext.Provider>
  );
}
